-- Loan Origination Portal - initial schema

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(255) NOT NULL,
    role          VARCHAR(32)  NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE borrower_profile (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT NOT NULL UNIQUE REFERENCES app_user(id),
    business_name         VARCHAR(255) NOT NULL,
    business_type         VARCHAR(120) NOT NULL,
    tax_id                VARCHAR(32)  NOT NULL,
    years_in_business     INT,
    annual_revenue_cents  BIGINT,
    address_line1         VARCHAR(255) NOT NULL,
    address_line2         VARCHAR(255),
    city                  VARCHAR(120) NOT NULL,
    state                 VARCHAR(2)   NOT NULL,
    postal_code           VARCHAR(16)  NOT NULL,
    contact_phone         VARCHAR(32)  NOT NULL,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE business_owner (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    borrower_profile_id BIGINT NOT NULL REFERENCES borrower_profile(id) ON DELETE CASCADE,
    full_name           VARCHAR(255) NOT NULL,
    title               VARCHAR(120) NOT NULL,
    ownership_pct       NUMERIC(5,2) NOT NULL,
    ssn_last4           VARCHAR(4)   NOT NULL,
    date_of_birth       VARCHAR(20)
);

CREATE TABLE lending_product (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(255) NOT NULL UNIQUE,
    description      VARCHAR(1000) NOT NULL,
    min_amount       NUMERIC(14,2) NOT NULL,
    max_amount       NUMERIC(14,2) NOT NULL,
    min_term_months  INT NOT NULL,
    max_term_months  INT NOT NULL,
    base_rate_pct    NUMERIC(5,2) NOT NULL,
    active           BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE loan_application (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    borrower_profile_id     BIGINT NOT NULL REFERENCES borrower_profile(id),
    lending_product_id      BIGINT NOT NULL REFERENCES lending_product(id),
    requested_amount        NUMERIC(14,2) NOT NULL,
    requested_term_months   INT NOT NULL,
    purpose                 VARCHAR(2000) NOT NULL,
    annual_revenue_cents    BIGINT,
    status                  VARCHAR(32) NOT NULL,
    risk_tier               VARCHAR(16) NOT NULL,
    assigned_underwriter_id BIGINT REFERENCES app_user(id),
    submitted_at            TIMESTAMPTZ,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_loan_application_borrower ON loan_application(borrower_profile_id);
CREATE INDEX idx_loan_application_status ON loan_application(status);
CREATE INDEX idx_loan_application_underwriter ON loan_application(assigned_underwriter_id);

CREATE TABLE document_type_template (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(64) NOT NULL UNIQUE,
    name           VARCHAR(255) NOT NULL,
    description    VARCHAR(1000) NOT NULL,
    required       BOOLEAN NOT NULL DEFAULT TRUE,
    active         BOOLEAN NOT NULL DEFAULT TRUE,
    validity_days  INT
);

CREATE TABLE document (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id      BIGINT NOT NULL REFERENCES loan_application(id),
    document_type_id    BIGINT NOT NULL REFERENCES document_type_template(id),
    status              VARCHAR(32) NOT NULL,
    stored_path         VARCHAR(500),
    original_filename   VARCHAR(255),
    content_type        VARCHAR(120),
    size_bytes          BIGINT,
    uploaded_by         BIGINT REFERENCES app_user(id),
    reviewed_by         BIGINT REFERENCES app_user(id),
    rejection_reason    VARCHAR(1000),
    expires_at          TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_document_application ON document(application_id);

CREATE TABLE underwriting_note (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES loan_application(id),
    author_id      BIGINT NOT NULL REFERENCES app_user(id),
    note           VARCHAR(4000) NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_note_application ON underwriting_note(application_id);

CREATE TABLE decision (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id            BIGINT NOT NULL REFERENCES loan_application(id),
    decision_type             VARCHAR(32) NOT NULL,
    risk_tier                 VARCHAR(16) NOT NULL,
    reasons                   VARCHAR(2000) NOT NULL,
    counteroffer_amount       NUMERIC(14,2),
    counteroffer_rate_pct     NUMERIC(5,2),
    counteroffer_term_months  INT,
    decided_by                BIGINT NOT NULL REFERENCES app_user(id),
    decided_at                TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_decision_application ON decision(application_id);

CREATE TABLE message (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES loan_application(id),
    sender_id      BIGINT NOT NULL REFERENCES app_user(id),
    body           VARCHAR(4000) NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_message_application ON message(application_id);

CREATE TABLE payment_account (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    borrower_profile_id  BIGINT NOT NULL REFERENCES borrower_profile(id),
    bank_name            VARCHAR(255) NOT NULL,
    account_type         VARCHAR(32) NOT NULL,
    account_last4        VARCHAR(4) NOT NULL,
    routing_last4        VARCHAR(4) NOT NULL,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE audit_event (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id  BIGINT REFERENCES app_user(id),
    action         VARCHAR(120) NOT NULL,
    entity_type    VARCHAR(80) NOT NULL,
    entity_id      BIGINT,
    before_state   VARCHAR(4000),
    after_state    VARCHAR(4000),
    auth_basis     VARCHAR(255) NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_entity ON audit_event(entity_type, entity_id);
CREATE INDEX idx_audit_actor ON audit_event(actor_user_id);

CREATE TABLE notification (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES app_user(id),
    message     VARCHAR(500) NOT NULL,
    link        VARCHAR(255),
    read        BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_notification_user ON notification(user_id, read);

CREATE TABLE outbox_email (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    to_address  VARCHAR(255) NOT NULL,
    subject     VARCHAR(500) NOT NULL,
    body        VARCHAR(8000) NOT NULL,
    status      VARCHAR(32) NOT NULL DEFAULT 'SENT',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE webhook_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type    VARCHAR(120) NOT NULL,
    payload       VARCHAR(4000) NOT NULL,
    status        VARCHAR(32) NOT NULL,
    attempted_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE password_reset_token (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES app_user(id),
    token_hash  VARCHAR(255) NOT NULL UNIQUE,
    expires_at  TIMESTAMPTZ NOT NULL,
    used        BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE borrower_lead (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_name  VARCHAR(255) NOT NULL,
    contact_email  VARCHAR(255) NOT NULL,
    contact_phone  VARCHAR(32),
    status         VARCHAR(32) NOT NULL DEFAULT 'NEW',
    import_batch   VARCHAR(80) NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
